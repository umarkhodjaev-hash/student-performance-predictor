// =========================
// CHANGE LANGUAGE
// =========================

function changeLanguage(lang) {

    const selectedLanguage = translations[lang];

    if (!selectedLanguage) {
        return;
    }


    document.querySelectorAll("[data-i18n]").forEach((element) => {

        const key = element.getAttribute("data-i18n");

        if (selectedLanguage[key] !== undefined) {

            element.textContent = selectedLanguage[key];

        } else if (translations.en[key] !== undefined) {

            // If a translation does not exist yet,
            // keep the English version.
            element.textContent = translations.en[key];

        }

    });


    // Save language
    localStorage.setItem("language", lang);


    // Change HTML language
    document.documentElement.lang = lang;


    // Arabic = RTL
    if (lang === "ar") {

        document.documentElement.dir = "rtl";

    } else {

        document.documentElement.dir = "ltr";

    }
}


// =========================
// INITIALIZE
// =========================

document.addEventListener("DOMContentLoaded", () => {

    const switcher =
        document.getElementById("languageSwitcher");


    if (!switcher) {
        return;
    }


    const savedLanguage =
        localStorage.getItem("language") || "en";


    const activeLanguage =
        translations[savedLanguage]
            ? savedLanguage
            : "en";


    switcher.value = activeLanguage;


    changeLanguage(activeLanguage);


    switcher.addEventListener("change", (event) => {

        changeLanguage(event.target.value);

    });

});